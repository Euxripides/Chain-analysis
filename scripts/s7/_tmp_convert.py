import json

src = r"E:\Code\远程虚拟机\harness\blockchain-platform\scripts\s7\_tmp_pairs.json"
dst = r"E:\Code\远程虚拟机\harness\blockchain-platform\scripts\s7\p4_route_matrix_v2_pairs.py"
pairs = json.load(open(src, encoding="utf-8"))
DQ = chr(34)
BS = chr(92)
NL = chr(10)


def py_literal(s):
    body = json.dumps(s)[1:-1]
    parts = []
    i = 0
    while i < len(body):
        j = min(i + 96, len(body))
        while j > i and body[j - 1] == BS:
            j -= 1
        parts.append(body[i:j])
        i = j
    lines = [DQ + p + DQ for p in parts]
    return "(" + NL + NL.join("    " + ln for ln in lines) + NL + ")"


out = [
    "# P4 matrix runner v2 replacement pairs.",
    "# Every pair must match EXACTLY ONCE in p4_route_matrix_gate_v1.py.",
    "# Generated by the v2 review; v1 and its evidence are never rewritten.",
    "",
    "PAIRS = []",
    "",
]
for old, new in pairs:
    out.append("PAIRS.append((")
    out.append(py_literal(old) + ",")
    out.append(py_literal(new) + ",")
    out.append("))")
    out.append("")
open(dst, "w", encoding="utf-8", newline=NL).write(NL.join(out) + NL)
print("WROTE pairs=%d bytes=%d" % (len(pairs), len(NL.join(out))))
